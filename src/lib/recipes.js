// Mengen auf das Körpergewicht skalieren (Referenz 70 kg), begrenzt auf 0,75–1,35.
export const scaleFor = (weightKg) => Math.min(1.35, Math.max(0.75, (Number(weightKg) || 70) / 70));

export function recipeNutrients(r, weightKg) {
  const f = scaleFor(weightKg);
  return nutrientsOf(r.items.map(([k, g]) => [k, g * f]));
}

// Mikronährstoffe, die eine Portion besonders gut abdeckt (≥ 25 % des Tagesbedarfs).
export function highlights(n, sex = 'm', min = 0.25) {
  const ref = REFERENCE[sex] || REFERENCE.m;
  return Object.entries(ref).map(([k, v]) => ({ key: k, label: NUTRIENTS[k].label, pct: n[k] / v })).filter((x) => x.pct >= min).sort((a, b) => b.pct - a.pct);
}

// In das Rezeptformat der App (wie KI-Rezepte) umwandeln – für Anzeige und Favoriten.
export function toRecipe(r, weightKg) {
  const f = scaleFor(weightKg), n = recipeNutrients(r, weightKg);
  return {
    name: r.name, catalogId: r.id, portionen: 1, zeitMin: r.min,
    zutaten: r.items.map(([k, g]) => ({ menge: '', zutat: amountText(k, g * f) })),
    schritte: r.steps, tip: r.tip,
    makros: { kcal: Math.round(n.kcal), kh: Math.round(n.kh), eiweiss: Math.round(n.eiweiss), fett: Math.round(n.fett) },
    mikro: Object.fromEntries(Object.keys(NUTRIENTS).map((k) => [k, Math.round(n[k] * 10) / 10])),
    tags: [...r.slots.map((s) => SLOTS.find((x) => x[0] === s)?.[1]), ...r.ctx.map((c) => CONTEXTS.find((x) => x[0] === c)?.[1]), r.diet].filter(Boolean),
  };
}

const DIET_OK = { alles: ['vegan', 'vegetarisch', 'fisch', 'fleisch'], 'wenig Fleisch': ['vegan', 'vegetarisch', 'fisch', 'fleisch'], pescetarisch: ['vegan', 'vegetarisch', 'fisch'], vegetarisch: ['vegan', 'vegetarisch'], vegan: ['vegan'] };
export const fitsDiet = (r, diet = 'alles') => (DIET_OK[diet] || DIET_OK.alles).includes(r.diet);

export function filterCatalog({ slot, ctx, diet, q } = {}) {
  const s = (q || '').toLowerCase().trim();
  return CATALOG.filter((r) => (!slot || r.slots.includes(slot)) && (!ctx || r.ctx.includes(ctx)) && fitsDiet(r, diet)
    && (!s || r.name.toLowerCase().includes(s) || r.items.some(([k]) => FOODS[k].name.toLowerCase().includes(s))));
}
